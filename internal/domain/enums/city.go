func (c City) String() string {
	idx := int(c)
	if idx >= len(FarsiCityNames) || idx < 1 {
		return "CityUnknown"
	}
	return FarsiCityNames[c]
}

func GetAllCities() []City {
	cities := make([]City, 0, int(CityCount)-1)
	for i := City(1); i < CityCount; i++ {
		cities = append(cities, i)
	}
	return cities
}

